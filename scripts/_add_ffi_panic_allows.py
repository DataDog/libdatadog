"""One-shot: insert // allow(ffi-panic-boundary) on current ast-grep hits."""

from __future__ import annotations

import json
import subprocess
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ALLOW = "allow(ffi-panic-boundary):"


def justification(path: str) -> str:
    if "datadog-sidecar-ffi/" in path:
        return "sidecar-ffi uses panic=abort; do not catch_unwind"
    if path.endswith("builder/expanded.rs"):
        return "generated by c_setters!; containment belongs in the template"
    return "existing uncontained export"


def already_allowed(lines: list[str], insert_at: int) -> bool:
    i = insert_at - 1
    while i >= 0:
        stripped = lines[i].strip()
        if not stripped:
            i -= 1
            continue
        if stripped.startswith("#[") or stripped.startswith("//!"):
            i -= 1
            continue
        return ALLOW in stripped
    return False


def main() -> int:
    proc = subprocess.run(
        [
            str(ROOT / "scripts/run-ast-grep.sh"),
            "--",
            "scan",
            "--filter",
            "ffi-extern-c-panic-containment|ffi-macro-emits-extern-c",
            "--json=compact",
            "--color",
            "never",
        ],
        cwd=ROOT,
        check=False,
        capture_output=True,
        text=True,
    )
    if proc.returncode not in (0, 1):
        sys.stderr.write(proc.stderr)
        return proc.returncode or 2
    hits = json.loads(proc.stdout or "[]")
    by_file: dict[str, set[int]] = defaultdict(set)
    for hit in hits:
        path = hit.get("file") or hit.get("path")
        start = hit["range"]["start"]["line"]
        by_file[path].add(start)

    inserted = 0
    for rel, starts in sorted(by_file.items()):
        path = ROOT / rel
        lines = path.read_text(encoding="utf-8").splitlines(keepends=True)
        why = justification(rel)
        for start in sorted(starts, reverse=True):
            if start < 0 or start >= len(lines):
                continue
            if already_allowed(lines, start):
                continue
            indent = lines[start][: len(lines[start]) - len(lines[start].lstrip())]
            comment = f"{indent}// {ALLOW} {why}\n"
            lines.insert(start, comment)
            inserted += 1
        path.write_text("".join(lines), encoding="utf-8")
        print(f"{rel}: +{len(starts)} sites")
    print(f"inserted {inserted} allow comments across {len(by_file)} files")
    return 0


if __name__ == "__main__":
    sys.exit(main())

/// The largest DogStatsD datagram over UDP.
pub const UDP_MAX_PAYLOAD: usize = 1432;
/// The largest DogStatsD datagram over a Unix domain socket.
pub const UDS_MAX_PAYLOAD: usize = 8192;
/// The longest DogStatsD line sent by default: a longer line than the
/// payload goes alone in a datagram of its own up to this, and only a
/// longer one is dropped.
pub const MAX_LINE_BYTES: usize = 8192;

// The header states the values; they are the crate's.
const _: () = assert!(UDP_MAX_PAYLOAD == DOGSTATSD_UDP_MAX_PAYLOAD);
const _: () = assert!(UDS_MAX_PAYLOAD == DOGSTATSD_UDS_MAX_PAYLOAD);
const _: () = assert!(MAX_LINE_BYTES == DOGSTATSD_MAX_LINE_BYTES);

/// How a call ended.
#[repr(C)]
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Status {
    /// The call succeeded; its output, if any, is in the buffer.
    Ok = 0,
    /// The input was rejected. For a JSON output the buffer holds
    /// `{"error": {"code", "message"}}`, whose code is stable; for a text
    /// output the buffer is empty.
    Rejected = 1,
    /// The call failed: a null pointer, text that is not UTF-8, or a panic
    /// that was caught. The buffer holds `{"error": ...}` when it can.
    Internal = 2,
}

/// Bytes owned by this library. Release them with
/// [`ddog_ai_usage_buffer_drop`].
#[repr(C)]
#[derive(Debug)]
pub struct Buffer {
    /// The first byte, or null for an empty buffer.
    pub ptr: *mut u8,
    /// The number of bytes.
    pub len: usize,
}

impl Buffer {
    const EMPTY: Buffer = Buffer {
        ptr: ptr::null_mut(),
        len: 0,
    };

    fn from_string(text: String) -> Buffer {
        Buffer::from_bytes(text.into_bytes())
    }

    fn from_bytes(bytes: Vec<u8>) -> Buffer {
        if bytes.is_empty() {
            return Buffer::EMPTY;
        }
        let bytes = bytes.into_boxed_slice();
        let len = bytes.len();
        Buffer {
            ptr: Box::into_raw(bytes).cast::<u8>(),
            len,
        }
    }
}

/// Projections collected over one export window. Safe to share between
/// threads.
pub struct Batch {
    inner: Mutex<MetricBatch>,
    settings: Mutex<BatchSettings>,
}

/// A provider stream being read. Use one from one thread at a time.
pub struct Stream {
    inner: UsageStream,
}

fn error_value(code: &str, message: &str) -> Value {
    json!({"error": {"code": code, "message": message}})
}

fn rejection(error: &MetricError) -> Value {
    error_value(error.code().as_str(), error.message())
}

/// Write `text` to `out`, which the caller checked is not null.
///
/// # Safety
///
/// `out` must be writable.
unsafe fn write(out: *mut Buffer, text: String) {
    // SAFETY: the caller guarantees `out` is writable.
    unsafe { out.write(Buffer::from_string(text)) };
}

/// The bytes `ptr[..len]`, or `None` for a null `ptr` with a non-zero `len`.
///
/// # Safety
///
/// `ptr` must point to `len` readable bytes, or `len` must be 0.
unsafe fn bytes<'a>(ptr: *const u8, len: usize) -> Option<&'a [u8]> {
    if len == 0 {
        return Some(&[]);
    }
    if ptr.is_null() {
        return None;
    }
    // SAFETY: the caller guarantees `len` readable bytes.
    Some(unsafe { slice::from_raw_parts(ptr, len) })
}

/// The UTF-8 text `ptr[..len]`, or `None` when it is null or not UTF-8.
///
/// # Safety
///
/// `ptr` must point to `len` readable bytes, or `len` must be 0.
unsafe fn text<'a>(ptr: *const u8, len: usize) -> Option<&'a str> {
    // SAFETY: forwarded from the caller.
    std::str::from_utf8(unsafe { bytes(ptr, len) }?).ok()
}

/// Run a call whose output is JSON: write its value, or its rejection, to
/// `out`, and catch any panic.
///
/// # Safety
///
/// `out` must be null or writable.
unsafe fn json_call(out: *mut Buffer, call: impl FnOnce() -> Result<Value, Failure>) -> Status {
    if out.is_null() {
        return Status::Internal;
    }
    let (status, value) = match catch_unwind(AssertUnwindSafe(call)) {
        Ok(Ok(value)) => (Status::Ok, value),
        Ok(Err(Failure::Rejected(error))) => (Status::Rejected, rejection(&error)),
        Ok(Err(Failure::Internal(message))) => (Status::Internal, error_value("internal", message)),
        Err(_) => (
            Status::Internal,
            error_value("internal", "the call panicked"),
        ),
    };
    let text = catch_unwind(|| value.to_string()).unwrap_or_default();
    // SAFETY: `out` is not null and the caller guarantees it is writable.
    unsafe { write(out, text) };
    status
}

/// Run a call whose output is text but whose failure is reported as JSON:
/// [`Status::Ok`] with the text in `out`, or the status with
/// `{"error": {"code", "message"}}` in `out`, as [`json_call`] writes it.
///
/// # Safety
///
/// `out` must be null or writable.
unsafe fn text_or_error_call(
    out: *mut Buffer,
    call: impl FnOnce() -> Result<String, Failure>,
) -> Status {
    if out.is_null() {
        return Status::Internal;
    }
    let (status, text) = match catch_unwind(AssertUnwindSafe(call)) {
        Ok(Ok(text)) => (Status::Ok, text),
        Ok(Err(Failure::Rejected(error))) => (Status::Rejected, rejection(&error).to_string()),
        Ok(Err(Failure::Internal(message))) => (
            Status::Internal,
            error_value("internal", message).to_string(),
        ),
        Err(_) => (
            Status::Internal,
            error_value("internal", "the call panicked").to_string(),
        ),
    };
    // SAFETY: `out` is not null and the caller guarantees it is writable.
    unsafe { write(out, text) };
    status
}

/// Write `count` to `out` when it is not null.
///
/// # Safety
///
/// `out` must be null or writable.
unsafe fn write_count(out: *mut usize, count: usize) {
    if !out.is_null() {
        // SAFETY: the caller guarantees `out` is writable.
        unsafe { out.write(count) };
    }
}

/// Comma-separated `key:value` tags, empty ones dropped.
fn constant_tags_of(tags: Option<&str>) -> Result<Vec<&str>, Failure> {
    let tags = tags.ok_or(Failure::Internal("constant_tags is not UTF-8"))?;
    Ok(tags
        .split(',')
        .map(str::trim)
        .filter(|tag| !tag.is_empty())
        .collect())
}

enum Failure {
    Rejected(MetricError),
    Internal(&'static str),
}

impl From<MetricError> for Failure {
    fn from(error: MetricError) -> Self {
        Failure::Rejected(error)
    }
}

fn invalid(message: impl Into<String>) -> Failure {
    Failure::Rejected(MetricError::new(ErrorCode::FieldTypeInvalid, message))
}

fn parse_document(input: Option<&[u8]>) -> Result<Json, Failure> {
    let input = input.ok_or(Failure::Internal("the input is null"))?;
    let text = std::str::from_utf8(input).map_err(|_| invalid("the input is not UTF-8"))?;
    Json::parse(text).map_err(|error| invalid(error.to_string()))
}

/// The projection a request document asks for: `profile`, `observation`,
/// optional `deployment_attributes`, and an optional `metrics` list that
/// keeps only those metrics.
fn projection_of(document: &Json) -> Result<(Profile, libdd_ai_usage::Projection), Failure> {
    projection_with(document, &BatchSettings::default())
}

/// The metric list and deployment attributes a batch applies to every
/// document that does not state its own.
#[derive(Default)]
struct BatchSettings {
    metrics: Option<Vec<String>>,
    deployment_attributes: Option<Json>,
}

/// [`projection_of`], with `defaults` for what the document leaves out.
fn projection_with(
    document: &Json,
    defaults: &BatchSettings,
) -> Result<(Profile, libdd_ai_usage::Projection), Failure> {
    let id = document
        .get("profile")
        .and_then(Json::as_str)
        .ok_or_else(|| MetricError::new(ErrorCode::RequiredFieldMissing, "profile is required"))?;
    let profile = Profile::from_id(id).ok_or_else(|| {
        MetricError::new(
            ErrorCode::ProfileInvalid,
            format!("unsupported profile: {id}"),
        )
    })?;
    let observation = document.get(profile.input_key()).unwrap_or(&Json::Null);
    let projection = project_extended(profile, observation)?;
    // The batch's attributes, with the document's on top: a document states
    // only what differs, and `null` for an attribute removes the batch's.
    let merged;
    let deployment = match (
        document.get("deployment_attributes"),
        &defaults.deployment_attributes,
    ) {
        (None | Some(Json::Null), Some(defaults)) => defaults,
        (None | Some(Json::Null), None) => &Json::Null,
        (Some(Json::Object(own)), Some(Json::Object(defaults))) => {
            let mut all = defaults.clone();
            all.extend(
                own.iter()
                    .map(|(name, value)| (name.clone(), value.clone())),
            );
            merged = Json::Object(all);
            &merged
        }
        (Some(attributes), _) => attributes,
    };
    let mut projection = with_deployment_attributes_json(projection, deployment)?;
    match document.get("metrics") {
        None | Some(Json::Null) => {
            if let Some(names) = &defaults.metrics {
                retain_metrics(&mut projection, names);
            }
        }
        Some(Json::Array(names)) => {
            let names = names
                .iter()
                .map(|name| {
                    name.as_str()
                        .ok_or_else(|| invalid("metrics must be strings"))
                })
                .collect::<Result<Vec<&str>, Failure>>()?;
            retain_metrics(&mut projection, &names);
        }
        Some(_) => return Err(invalid("metrics must be an array of strings")),
    }
    Ok((profile, projection))
}

fn issues(projection: &libdd_ai_usage::Projection) -> Value {
    json!(
        projection
            .issues
            .iter()
            .map(|issue| issue.as_str())
            .collect::<Vec<_>>()
    )
}

/// Project the request document `input[..input_len]` into its Datadog
/// series and write `{"series": [{"name", "type", "value", "tags"}],
/// "issues": [...]}` to `out`.
///
/// The document is `{"profile": "{id}@{version}", "observation": {...},
/// "deployment_attributes": {...}, "metrics": [...]}`; the last two are
/// optional.
///
/// # Safety
///
/// `input` must point to `input_len` readable bytes (or `input_len` must be
/// 0), and `out` must be null or point to a writable [`Buffer`], released
/// with [`ddog_ai_usage_buffer_drop`].
#[unsafe(no_mangle)]
pub unsafe extern "C" fn ddog_ai_usage_project(
    input: *const u8,
    input_len: usize,
    out: *mut Buffer,
) -> Status {
    // SAFETY: forwarded from the caller.
    unsafe {
        json_call(out, || {
            catch_unwind(AssertUnwindSafe(|| {
                let document = parse_document(bytes(input, input_len))?;
                let (profile, projection) = projection_of(&document)?;
                let series =
                    datadog_series(profile, &projection.points, &projection.resource, false)?;
                Ok(json!({
                    "series": series
                        .iter()
                        .map(|s| json!({
                            "name": s.name,
                            "type": s.series_type.as_str(),
                            "value": s.value,
                            "tags": s.tags,
                        }))
                        .collect::<Vec<_>>(),
                    "issues": issues(&projection),
                }))
            }))
            .unwrap_or(Err(Failure::Internal("the projection panicked")))
        })
    }
}

/// Project the request document `input[..input_len]`, as
/// [`ddog_ai_usage_project`] reads it, and write its DogStatsD lines to
/// `out` as text: one line per series, separated by `\n`, without a trailing
/// newline. The lines are this observation's alone (never merged with
/// another's) and in a fixed order (by name, then tags). Pack them with
/// [`ddog_ai_usage_pack_dogstatsd_lines`]. No JSON is built for the output,
/// so a caller that sends each observation as it ends parses nothing. The
/// issues of the projection are not reported; use [`ddog_ai_usage_project`]
/// for them. A rejected document writes `{"error": {"code", "message"}}`, as
/// [`ddog_ai_usage_project`] does.
///
/// # Safety
///
/// `input` must point to `input_len` readable bytes (or `input_len` must be
/// 0), and `out` must be null or writable.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn ddog_ai_usage_dogstatsd_lines(
    input: *const u8,
    input_len: usize,
    out: *mut Buffer,
) -> Status {
    // SAFETY: forwarded from the caller.
    unsafe {
        text_or_error_call(out, || {
            catch_unwind(AssertUnwindSafe(|| {
                let document = parse_document(bytes(input, input_len))?;
                let (profile, projection) = projection_of(&document)?;
                let series =
                    datadog_series(profile, &projection.points, &projection.resource, false)?;
                let mut text = String::with_capacity(series.len() * 128);
                for (at, s) in series.iter().enumerate() {
                    if at > 0 {
                        text.push('\n');
                    }
                    text.push_str(&s.to_dogstatsd());
                }
                Ok(text)
            }))
            .unwrap_or(Err(Failure::Internal("the projection panicked")))
        })
    }
}

/// Pack the DogStatsD lines `lines[..lines_len]` (separated by `\n`; a `\r`
/// before it and empty lines are dropped) into datagrams of at most
/// `max_payload` bytes, with the comma-separated `constant_tags` appended to
/// each line, and write them to `out` as text: each datagram's lines joined
/// by `\n`, datagrams separated by a NUL byte, no trailing NUL. Neither the
/// input nor the output is JSON. A line longer than `max_payload` with its
/// tags (one with many tags can pass [`UDP_MAX_PAYLOAD`]) is sent alone in a
/// datagram of its own; only a line longer than [`MAX_LINE_BYTES`] (or
/// `max_payload`, if larger) is dropped, as the Agent would refuse it, and
/// the number dropped is written to `dropped_lines` when it is not null.
/// [`Status::Rejected`] for a `max_payload` of 0.
///
/// # Safety
///
/// `lines` and `constant_tags` must point to their lengths of readable bytes
/// (or the length must be 0), `dropped_lines` must be null or writable, and
/// `out` must be null or writable.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn ddog_ai_usage_pack_dogstatsd_lines(
    lines: *const u8,
    lines_len: usize,
    constant_tags: *const u8,
    constant_tags_len: usize,
    max_payload: usize,
    dropped_lines: *mut usize,
    out: *mut Buffer,
) -> Status {
    // SAFETY: forwarded from the caller.
    unsafe {
        text_or_error_call(out, || {
            catch_unwind(AssertUnwindSafe(|| {
                let lines = text(lines, lines_len)
                    .ok_or(Failure::Internal("lines are null or not UTF-8"))?;
                let tags = constant_tags_of(text(constant_tags, constant_tags_len))?;
                if max_payload == 0 {
                    return Err(invalid("max_payload must be a positive integer"));
                }
                let lines = lines
                    .split('\n')
                    .map(|line| line.strip_suffix('\r').unwrap_or(line));
                let (text, dropped) = pack_dogstatsd_joined(lines, &tags, max_payload, '\0');
                write_count(dropped_lines, dropped);
                Ok(text)
            }))
            .unwrap_or(Err(Failure::Internal("packing panicked")))
        })
    }
}

/// Create an empty [`Batch`] and write it to `out`. Release it with
/// [`ddog_ai_usage_batch_drop`].
///
/// # Safety
///
/// `out` must be null or writable.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn ddog_ai_usage_batch_new(out: *mut *mut Batch) -> Status {
    if out.is_null() {
        return Status::Internal;
    }
    let batch = catch_unwind(|| {
        Box::into_raw(Box::new(Batch {
            inner: Mutex::new(MetricBatch::new()),
            settings: Mutex::new(BatchSettings::default()),
        }))
    });
    match batch {
        Ok(batch) => {
            // SAFETY: `out` is not null and the caller guarantees it is
            // writable.
            unsafe { out.write(batch) };
            Status::Ok
        }
        Err(_) => Status::Internal,
    }
}

/// Project the request document `input[..input_len]`, as
/// [`ddog_ai_usage_project`] reads it, and add its points to `batch`. Writes
/// `{"issues": [...], "dropped": false, "full": false}` to `out` (`full`
/// when the batch reached its high-water mark, see
/// [`ddog_ai_usage_batch_set_high_water`]). A rejected document adds
/// nothing. `dropped` is true when a bounded batch (see
/// [`ddog_ai_usage_batch_set_max_len`]) had no room for the observation,
/// which then adds nothing and is counted by [`ddog_ai_usage_batch_dropped`];
/// the status is still [`Status::Ok`].
///
/// # Safety
///
/// `batch` must be a live batch from [`ddog_ai_usage_batch_new`], `input`
/// must point to `input_len` readable bytes (or `input_len` must be 0), and
/// `out` must be null or writable.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn ddog_ai_usage_batch_add(
    batch: *const Batch,
    input: *const u8,
    input_len: usize,
    out: *mut Buffer,
) -> Status {
    // SAFETY: forwarded from the caller.
    unsafe {
        json_call(out, || {
            catch_unwind(AssertUnwindSafe(|| {
                // SAFETY: the caller guarantees a live batch or null.
                let batch = batch
                    .as_ref()
                    .ok_or(Failure::Internal("the batch is null"))?;
                let (issues, added, full) = add_document(batch, bytes(input, input_len), true)?;
                Ok(json!({"issues": issues, "dropped": !added, "full": full}))
            }))
            .unwrap_or(Err(Failure::Internal("adding to the batch panicked")))
        })
    }
}

/// Project a request document with the batch's settings and add it,
/// returning its issues (when asked for), whether it was added, and whether
/// the batch reached its high-water mark.
fn add_document(
    batch: &Batch,
    input: Option<&[u8]>,
    want_issues: bool,
) -> Result<(Option<Value>, bool, bool), Failure> {
    let document = parse_document(input)?;
    let (profile, projection) = {
        let settings = batch
            .settings
            .lock()
            .map_err(|_| Failure::Internal("the batch is poisoned"))?;
        projection_with(&document, &settings)?
    };
    let issues = want_issues.then(|| issues(&projection));
    let mut inner = batch
        .inner
        .lock()
        .map_err(|_| Failure::Internal("the batch is poisoned"))?;
    let added = inner.try_add_owned(profile, projection)?;
    Ok((issues, added, inner.is_full()))
}

/// [`ddog_ai_usage_batch_add`] without its output: nothing is written on
/// success, so a gateway that does not read the issues builds no JSON. A
/// rejected document writes `{"error": {"code", "message"}}` to `out` when
/// `out` is not null. Whether a bounded batch dropped the observation is
/// counted by [`ddog_ai_usage_batch_dropped`].
///
/// # Safety
///
/// As [`ddog_ai_usage_batch_add`]; `out` may be null.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn ddog_ai_usage_batch_add_quiet(
    batch: *const Batch,
    input: *const u8,
    input_len: usize,
    out: *mut Buffer,
) -> Status {
    let result = catch_unwind(AssertUnwindSafe(|| {
        // SAFETY: the caller guarantees a live batch or null.
        let batch = unsafe { batch.as_ref() }.ok_or(Failure::Internal("the batch is null"))?;
        // SAFETY: forwarded from the caller.
        add_document(batch, unsafe { bytes(input, input_len) }, false).map(|_| ())
    }))
    .unwrap_or(Err(Failure::Internal("adding to the batch panicked")));
    let (status, error) = match result {
        Ok(()) => return Status::Ok,
        Err(Failure::Rejected(error)) => (Status::Rejected, rejection(&error)),
        Err(Failure::Internal(message)) => (Status::Internal, error_value("internal", message)),
    };
    if !out.is_null() {
        // SAFETY: `out` is not null and the caller guarantees it is writable.
        unsafe { write(out, error.to_string()) };
    }
    status
}

/// Add every observation of one request to `batch` together: `input[..input_len]`
/// is a JSON array of request documents, each as [`ddog_ai_usage_batch_add`]
/// reads it (its provider attempts, token breakdowns and gateway request).
/// Either all are added or none: a bounded batch without room for all of
/// them drops them all, so it never keeps an attempt without its breakdown,
/// and counts each in [`ddog_ai_usage_batch_dropped`]. A rejected document
/// rejects the request, adds nothing, and writes `{"error": {"code",
/// "message"}}` whose message names the document's index. On success writes
/// `{"issues": [[...], ...], "dropped": false, "full": false}` (one issue
/// list per document; `full` when the batch reached its high-water mark, see
/// [`ddog_ai_usage_batch_set_high_water`]) to `out`, or nothing when `out` is
/// null.
///
/// # Safety
///
/// `batch` must be a live batch from [`ddog_ai_usage_batch_new`], `input`
/// must point to `input_len` readable bytes (or `input_len` must be 0), and
/// `out` must be null or writable.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn ddog_ai_usage_batch_add_request(
    batch: *const Batch,
    input: *const u8,
    input_len: usize,
    out: *mut Buffer,
) -> Status {
    let want_output = !out.is_null();
    let result = catch_unwind(AssertUnwindSafe(|| {
        // SAFETY: the caller guarantees a live batch or null.
        let batch = unsafe { batch.as_ref() }.ok_or(Failure::Internal("the batch is null"))?;
        // SAFETY: forwarded from the caller.
        let request = parse_document(unsafe { bytes(input, input_len) })?;
        let documents = request
            .as_array()
            .ok_or_else(|| invalid("a request must be an array of documents"))?;
        let projections = {
            let settings = batch
                .settings
                .lock()
                .map_err(|_| Failure::Internal("the batch is poisoned"))?;
            documents
                .iter()
                .enumerate()
                .map(|(at, document)| {
                    projection_with(document, &settings).map_err(|failure| match failure {
                        Failure::Rejected(error) => Failure::Rejected(MetricError::new(
                            error.code(),
                            format!("document {at}: {}", error.message()),
                        )),
                        internal => internal,
                    })
                })
                .collect::<Result<Vec<_>, Failure>>()?
        };
        let issues = want_output.then(|| {
            projections
                .iter()
                .map(|(_, projection)| issues(projection))
                .collect::<Vec<Value>>()
        });
        let mut inner = batch
            .inner
            .lock()
            .map_err(|_| Failure::Internal("the batch is poisoned"))?;
        let added = inner.try_add_all(projections)?;
        Ok((issues, added, inner.is_full()))
    }))
    .unwrap_or(Err(Failure::Internal("adding to the batch panicked")));
    let (status, value) = match result {
        Ok((Some(issues), added, full)) => (
            Status::Ok,
            json!({"issues": issues, "dropped": !added, "full": full}),
        ),
        Ok((None, ..)) => return Status::Ok,
        Err(Failure::Rejected(error)) => (Status::Rejected, rejection(&error)),
        Err(Failure::Internal(message)) => (Status::Internal, error_value("internal", message)),
    };
    if want_output {
        let text = catch_unwind(|| value.to_string()).unwrap_or_default();
        // SAFETY: `out` is not null and the caller guarantees it is writable.
        unsafe { write(out, text) };
    }
    status
}


#[cfg(all(feature = "catch_panic", panic = "unwind"))]
macro_rules! catch_panic {
    ($f:expr, $err:expr) => {
        match std::panic::catch_unwind(std::panic::AssertUnwindSafe(|| $f)) {
            Ok(ret) => ret,
            Err(_) => $err,
        }
    };
}

#[cfg(any(not(feature = "catch_panic"), panic = "abort"))]
macro_rules! catch_panic {
    ($f:expr, $err:expr) => {{
        // `$err` only runs when panics are caught; naming it keeps what it
        // uses in use.
        let _ = || $err;
        // A closure, so that a `return` in `$f` means what it does above.
        #[allow(clippy::redundant_closure_call)]
        let result = (|| $f)();
        result
    }};
}

pub(crate) use catch_panic;

/// The version of this C ABI, which [`ddog_ai_usage_abi_version`] returns.
///
/// Bumped on any breaking change to the C ABI: a function removed, renamed or
/// given other parameters, a structure or enumeration changed, or a JSON
/// output changed in a way a binding reads. A binding checks it when it loads
/// the library and refuses a version other than the one it was written for.
/// Version 2 moved the interface to libdatadog's common FFI types; its JSON
/// outputs are those of version 1.
pub const ABI_VERSION: u32 = 2;

/// The largest DogStatsD datagram over UDP.
pub const UDP_MAX_PAYLOAD: usize = 1432;
/// The largest DogStatsD datagram over a Unix domain socket.
pub const UDS_MAX_PAYLOAD: usize = 8192;
/// The longest DogStatsD line sent by default: a longer line than the
/// payload goes alone in a datagram of its own up to this, and only a
/// longer one is dropped.
pub const MAX_LINE_BYTES: usize = 8192;

// The header states the values; they are the crate's.
const _: () = assert!(UDP_MAX_PAYLOAD == DOGSTATSD_UDP_MAX_PAYLOAD);
const _: () = assert!(UDS_MAX_PAYLOAD == DOGSTATSD_UDS_MAX_PAYLOAD);
const _: () = assert!(MAX_LINE_BYTES == DOGSTATSD_MAX_LINE_BYTES);

/// The version of the C ABI this library implements, [`ABI_VERSION`]. A
/// binding calls it once when it loads the library and refuses to use a
/// library whose version differs from the one it was written for.
// allow(ffi-panic-boundary): returns a constant; it cannot panic.
#[unsafe(no_mangle)]
pub extern "C" fn ddog_ai_usage_abi_version() -> u32 {
    ABI_VERSION
}

/// The bytes of a slice, or `None` for a null pointer with a length.
fn bytes<'a>(slice: impl AsBytes<'a>) -> Option<&'a [u8]> {
    slice.try_as_bytes().ok()
}

/// The UTF-8 text of a slice, or `None` when it is null or not UTF-8.
fn text(slice: CharSlice<'_>) -> Option<&str> {
    std::str::from_utf8(bytes(slice)?).ok()
}

fn invalid(message: impl Into<String>) -> Failure {
    Failure::Rejected(MetricError::new(ErrorCode::FieldTypeInvalid, message))
}

/// A value of the core crate as the JSON text this interface writes: built
/// as a `serde_json::Value` first, as ABI v1 wrote it, so the text is the
/// same byte for byte.
fn json_text(value: Result<Value, serde_json::Error>) -> Result<String, Failure> {
    value
        .map(|value| value.to_string())
        .map_err(|_| Failure::Internal("the output could not be written"))
}

fn parse_document(input: CharSlice<'_>) -> Result<Json, Failure> {
    let input = bytes(input).ok_or(Failure::Internal("the input is null"))?;
    let text = std::str::from_utf8(input).map_err(|_| invalid("the input is not UTF-8"))?;
    Json::parse(text).map_err(|error| invalid(error.to_string()))
}

/// Run `call` and write its text to `out`, or an empty string when it
/// fails, and return its error. A null `out` is an internal error and
/// `call` does not run.
///
/// # Safety
///
/// `out` must be null or point to memory a `ddog_StringWrapper` can be
/// written to; what it held is not released.
unsafe fn write_output(
    out: *mut StringWrapper,
    call: impl FnOnce() -> Result<String, Failure>,
) -> Option<Box<AiUsageError>> {
    if out.is_null() {
        return Some(Failure::Internal("the output is null").into());
    }
    let (text, error) = match call() {
        Ok(text) => (text, None),
        Err(failure) => (String::new(), Some(failure.into())),
    };
    // SAFETY: `out` is not null and the caller guarantees it is writable.
    unsafe { out.write(StringWrapper::from(text)) };
    error
}

/// The error of a call that panicked, with an empty `out` when it is not
/// null.
///
/// # Safety
///
/// As [`write_output`].
unsafe fn panicked_output(out: *mut StringWrapper) -> Option<Box<AiUsageError>> {
    if !out.is_null() {
        // SAFETY: `out` is not null and the caller guarantees it is writable.
        unsafe { out.write(StringWrapper::from(String::new())) };
    }
    panicked()
}

/// The value a handle holds, borrowed shared, or `None` for a null or
/// released handle. `ToInner::to_inner_mut` borrows it exclusively, which a
/// [`Batch`] used from several threads at once must not be.
///
/// # Safety
///
/// `handle` must be null or point to a handle this library wrote, whose value
/// is not released during the borrow.
unsafe fn shared<'a, T>(handle: *const Handle<T>) -> Option<&'a T> {
    // A `Handle<T>` is `#[repr(C)] struct { T *inner; }`, the layout the C
    // header states: the pointer to its value, null once released.
    // SAFETY: the caller guarantees a readable handle or null.
    let inner = unsafe { handle.cast::<*const T>().as_ref() }?;
    // SAFETY: a non-null `inner` points to the live value.
    unsafe { inner.as_ref() }
}

const _: () = assert!(size_of::<Handle<Batch>>() == size_of::<*const Batch>());
const _: () = assert!(size_of::<Handle<Stream>>() == size_of::<*const Stream>());

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_null_output_is_internal_and_the_call_does_not_run() {
        let mut ran = false;
        // SAFETY: a null output.
        let error = unsafe {
            write_output(std::ptr::null_mut(), || {
                ran = true;
                Ok(String::new())
            })
        }
        .unwrap();
        assert!(!ran);
        assert_eq!(error.code, AiUsageErrorCode::Internal);
    }

    #[test]
    fn a_failure_writes_an_empty_output() {
        let mut out = std::mem::MaybeUninit::<StringWrapper>::uninit();
        // SAFETY: `out` is writable.
        let error =
            unsafe { write_output(out.as_mut_ptr(), || Err(Failure::NoMatch("nothing"))) }.unwrap();
        assert_eq!(error.code, AiUsageErrorCode::NoMatch);
        // SAFETY: written by `write_output`.
        let out = unsafe { out.assume_init() };
        assert_eq!(String::from(out), "");
    }

    #[cfg(all(feature = "catch_panic", panic = "unwind"))]
    #[test]
    fn a_panic_is_an_internal_error_with_an_empty_output() {
        let mut out = std::mem::MaybeUninit::<StringWrapper>::uninit();
        let out = out.as_mut_ptr();
        let error = catch_panic!(
            // SAFETY: `out` is writable.
            unsafe { write_output(out, || panic!("boom")) },
            // SAFETY: `out` is writable.
            unsafe { panicked_output(out) }
        )
        .unwrap();
        assert_eq!(error.code, AiUsageErrorCode::Internal);
        assert_eq!(error.message.to_string(), "the call panicked");
        // SAFETY: written by `panicked_output`.
        assert_eq!(String::from(unsafe { out.read() }), "");
    }

    #[test]
    fn a_released_handle_is_none() {
        let mut handle = Handle::from(5u8);
        // SAFETY: a live handle.
        assert_eq!(unsafe { shared(&handle) }, Some(&5));
        // SAFETY: a live handle, taken once.
        drop(unsafe { libdd_common_ffi::ToInner::take(&mut handle) });
        // SAFETY: a released handle.
        assert_eq!(unsafe { shared(&handle) }, None);
        // SAFETY: null.
        assert_eq!(unsafe { shared::<u8>(std::ptr::null()) }, None);
    }
}

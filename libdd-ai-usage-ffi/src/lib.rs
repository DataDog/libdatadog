/// The lower-case names of the response headers
/// [`ddog_ai_usage_provider_ids`] reads for the provider
/// `provider_name[..provider_name_len]` (a `gen_ai.provider.name`, such as
/// `openai`), so a gateway fetches exactly those: writes `["openai-organization",
/// "openai-project"]`. An empty name lists the headers of every provider; a
/// provider whose ids come from no header has none.
///
/// # Safety
///
/// `provider_name` must point to `provider_name_len` readable bytes (or
/// `provider_name_len` must be 0), and `out` must be null or writable.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn ddog_ai_usage_provider_id_headers(
    provider_name: *const u8,
    provider_name_len: usize,
    out: *mut Buffer,
) -> Status {
    // SAFETY: forwarded from the caller.
    unsafe {
        json_call(out, || {
            catch_unwind(AssertUnwindSafe(|| {
                let provider = text(provider_name, provider_name_len)
                    .ok_or(Failure::Internal("provider_name is not UTF-8"))?;
                let mut headers: Vec<&str> = Vec::new();
                for (name, _, header) in PROVIDER_ID_HEADERS {
                    if (provider.is_empty() || provider == name) && !headers.contains(&header) {
                        headers.push(header);
                    }
                }
                Ok(json!(headers))
            }))
            .unwrap_or(Err(Failure::Internal("listing the headers panicked")))
        })
    }
}

/// The deployment attributes a provider's response names, from the request
/// document `input[..input_len]`: `{"provider_name": "anthropic",
/// "headers": {"anthropic-organization-id": "..."}, "models": ["arn:..."]}`.
/// Header names are matched in lower case. Writes `{attribute: value}`:
/// `trajectory.request.provider_account_id` and
/// `trajectory.request.project_id` from the provider's headers, or for
/// `aws.bedrock` the account a model ARN names. Without a `provider_name`
/// (absent or empty), every known header and the model ARNs are tried, as
/// [`ddog_ai_usage_provider_id_headers`] lists them for an empty name.
///
/// # Safety
///
/// `input` must point to `input_len` readable bytes (or `input_len` must be
/// 0), and `out` must be null or writable.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn ddog_ai_usage_provider_ids(
    input: *const u8,
    input_len: usize,
    out: *mut Buffer,
) -> Status {
    // SAFETY: forwarded from the caller.
    unsafe {
        json_call(out, || {
            catch_unwind(AssertUnwindSafe(|| {
                let document = parse_document(bytes(input, input_len))?;
                let provider = document
                    .get("provider_name")
                    .and_then(Json::as_str)
                    .unwrap_or_default();
                let headers: Vec<(String, &str)> = document
                    .get("headers")
                    .and_then(Json::as_object)
                    .map(|headers| {
                        headers
                            .iter()
                            .filter_map(|(name, value)| {
                                Some((name.to_ascii_lowercase(), value.as_str()?))
                            })
                            .collect()
                    })
                    .unwrap_or_default();
                let mut attributes: Attributes = provider_id_attributes(provider, |name| {
                    headers
                        .iter()
                        .find(|(header, _)| header == name)
                        .map(|(_, value)| *value)
                });
                if provider.is_empty() || provider == "aws.bedrock" {
                    let account = document
                        .get("models")
                        .and_then(Json::as_array)
                        .unwrap_or_default()
                        .iter()
                        .filter_map(Json::as_str)
                        .find_map(bedrock_arn_account);
                    if let Some(account) = account {
                        attributes
                            .entry("trajectory.request.provider_account_id".to_string())
                            .or_insert_with(|| account.to_string());
                    }
                }
                Ok(json!(attributes))
            }))
            .unwrap_or(Err(Failure::Internal("reading the ids panicked")))
        })
    }
}

/// Pack DogStatsD lines into datagrams, from the request document
/// `input[..input_len]`: `{"lines": [...], "constant_tags": [...],
/// "max_payload": 1432, "max_line_bytes": 8192}` (`constant_tags` optional,
/// `max_payload` defaults to [`UDP_MAX_PAYLOAD`], `max_line_bytes` to
/// [`MAX_LINE_BYTES`]). Writes `{"datagrams": [...], "dropped_lines": 0}`. A
/// line longer than `max_payload` with its tags goes alone in a datagram of
/// its own; one longer than `max_line_bytes` (or `max_payload`, if larger)
/// is dropped and counted.
///
/// # Safety
///
/// `input` must point to `input_len` readable bytes (or `input_len` must be
/// 0), and `out` must be null or writable.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn ddog_ai_usage_pack_dogstatsd(
    input: *const u8,
    input_len: usize,
    out: *mut Buffer,
) -> Status {
    // SAFETY: forwarded from the caller.
    unsafe {
        json_call(out, || {
            catch_unwind(AssertUnwindSafe(|| {
                let document = parse_document(bytes(input, input_len))?;
                let strings = |key: &str| -> Result<Vec<&str>, Failure> {
                    match document.get(key) {
                        None | Some(Json::Null) => Ok(Vec::new()),
                        Some(Json::Array(items)) => items
                            .iter()
                            .map(|item| {
                                item.as_str()
                                    .ok_or_else(|| invalid(format!("{key} must be strings")))
                            })
                            .collect(),
                        Some(_) => Err(invalid(format!("{key} must be an array"))),
                    }
                };
                let size = |key: &str, default: usize| -> Result<usize, Failure> {
                    match document.get(key) {
                        None | Some(Json::Null) => Ok(default),
                        Some(value) => value
                            .as_f64()
                            .filter(|n| n.is_finite() && *n >= 1.0 && n.fract() == 0.0)
                            // Whole and at least 1; a larger value than usize
                            // holds saturates, which no datagram reaches.
                            .map(|n| n as usize)
                            .ok_or_else(|| invalid(format!("{key} must be a positive integer"))),
                    }
                };
                let max_payload = size("max_payload", UDP_MAX_PAYLOAD)?;
                let max_line = size("max_line_bytes", MAX_LINE_BYTES)?;
                let (datagrams, dropped) = pack_dogstatsd_limited(
                    &strings("lines")?,
                    &strings("constant_tags")?,
                    max_payload,
                    max_line,
                );
                Ok(json!({"datagrams": datagrams, "dropped_lines": dropped}))
            }))
            .unwrap_or(Err(Failure::Internal("packing panicked")))
        })
    }
}


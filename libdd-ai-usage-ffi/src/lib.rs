/// The largest DogStatsD datagram over UDP.
pub const UDP_MAX_PAYLOAD: usize = 1432;
/// The largest DogStatsD datagram over a Unix domain socket.
pub const UDS_MAX_PAYLOAD: usize = 8192;
/// The longest DogStatsD line sent by default: a longer line than the
/// payload goes alone in a datagram of its own up to this, and only a
/// longer one is dropped.
pub const MAX_LINE_BYTES: usize = 8192;

// The header states the values; they are the crate's.
const _: () = assert!(UDP_MAX_PAYLOAD == DOGSTATSD_UDP_MAX_PAYLOAD);
const _: () = assert!(UDS_MAX_PAYLOAD == DOGSTATSD_UDS_MAX_PAYLOAD);
const _: () = assert!(MAX_LINE_BYTES == DOGSTATSD_MAX_LINE_BYTES);

/// How a call ended.
#[repr(C)]
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Status {
    /// The call succeeded; its output, if any, is in the buffer.
    Ok = 0,
    /// The input was rejected. For a JSON output the buffer holds
    /// `{"error": {"code", "message"}}`, whose code is stable; for a text
    /// output the buffer is empty.
    Rejected = 1,
    /// The call failed: a null pointer, text that is not UTF-8, or a panic
    /// that was caught. The buffer holds `{"error": ...}` when it can.
    Internal = 2,
}

/// Bytes owned by this library. Release them with
/// [`ddog_ai_usage_buffer_drop`].
#[repr(C)]
#[derive(Debug)]
pub struct Buffer {
    /// The first byte, or null for an empty buffer.
    pub ptr: *mut u8,
    /// The number of bytes.
    pub len: usize,
}

impl Buffer {
    const EMPTY: Buffer = Buffer {
        ptr: ptr::null_mut(),
        len: 0,
    };

    fn from_string(text: String) -> Buffer {
        Buffer::from_bytes(text.into_bytes())
    }

    fn from_bytes(bytes: Vec<u8>) -> Buffer {
        if bytes.is_empty() {
            return Buffer::EMPTY;
        }
        let bytes = bytes.into_boxed_slice();
        let len = bytes.len();
        Buffer {
            ptr: Box::into_raw(bytes).cast::<u8>(),
            len,
        }
    }
}

/// Projections collected over one export window. Safe to share between
/// threads.
pub struct Batch {
    inner: Mutex<MetricBatch>,
    settings: Mutex<BatchSettings>,
}

/// A provider stream being read. Use one from one thread at a time.
pub struct Stream {
    inner: UsageStream,
    /// Report usage with inclusive totals ([`INCLUSIVE_TOTALS`]).
    inclusive: bool,
}

/// An option of [`ddog_ai_usage_parse_provider_response_with`] and
/// [`ddog_ai_usage_stream_new_with`]: report usage with inclusive totals,
/// cache reads and writes added to an input that excludes them and
/// reasoning added to an output that excludes it, both bases then
/// `includes_*`.
pub const INCLUSIVE_TOTALS: u32 = 1;

fn error_value(code: &str, message: &str) -> Value {
    json!({"error": {"code": code, "message": message}})
}

fn rejection(error: &MetricError) -> Value {
    error_value(error.code().as_str(), error.message())
}

/// Write `text` to `out`, which the caller checked is not null.
///
/// # Safety
///
/// `out` must be writable.
unsafe fn write(out: *mut Buffer, text: String) {
    // SAFETY: the caller guarantees `out` is writable.
    unsafe { out.write(Buffer::from_string(text)) };
}

/// The bytes `ptr[..len]`, or `None` for a null `ptr` with a non-zero `len`.
///
/// # Safety
///
/// `ptr` must point to `len` readable bytes, or `len` must be 0.
unsafe fn bytes<'a>(ptr: *const u8, len: usize) -> Option<&'a [u8]> {
    if len == 0 {
        return Some(&[]);
    }
    if ptr.is_null() {
        return None;
    }
    // SAFETY: the caller guarantees `len` readable bytes.
    Some(unsafe { slice::from_raw_parts(ptr, len) })
}

/// The UTF-8 text `ptr[..len]`, or `None` when it is null or not UTF-8.
///
/// # Safety
///
/// `ptr` must point to `len` readable bytes, or `len` must be 0.
unsafe fn text<'a>(ptr: *const u8, len: usize) -> Option<&'a str> {
    // SAFETY: forwarded from the caller.
    std::str::from_utf8(unsafe { bytes(ptr, len) }?).ok()
}

/// Run a call whose output is JSON: write its value, or its rejection, to
/// `out`, and catch any panic.
///
/// # Safety
///
/// `out` must be null or writable.
unsafe fn json_call(out: *mut Buffer, call: impl FnOnce() -> Result<Value, Failure>) -> Status {
    if out.is_null() {
        return Status::Internal;
    }
    let (status, value) = match catch_unwind(AssertUnwindSafe(call)) {
        Ok(Ok(value)) => (Status::Ok, value),
        Ok(Err(Failure::Rejected(error))) => (Status::Rejected, rejection(&error)),
        Ok(Err(Failure::Internal(message))) => (Status::Internal, error_value("internal", message)),
        Err(_) => (
            Status::Internal,
            error_value("internal", "the call panicked"),
        ),
    };
    let text = catch_unwind(|| value.to_string()).unwrap_or_default();
    // SAFETY: `out` is not null and the caller guarantees it is writable.
    unsafe { write(out, text) };
    status
}

/// Run a call whose output is text but whose failure is reported as JSON:
/// [`Status::Ok`] with the text in `out`, or the status with
/// `{"error": {"code", "message"}}` in `out`, as [`json_call`] writes it.
///
/// # Safety
///
/// `out` must be null or writable.
unsafe fn text_or_error_call(
    out: *mut Buffer,
    call: impl FnOnce() -> Result<String, Failure>,
) -> Status {
    if out.is_null() {
        return Status::Internal;
    }
    let (status, text) = match catch_unwind(AssertUnwindSafe(call)) {
        Ok(Ok(text)) => (Status::Ok, text),
        Ok(Err(Failure::Rejected(error))) => (Status::Rejected, rejection(&error).to_string()),
        Ok(Err(Failure::Internal(message))) => (
            Status::Internal,
            error_value("internal", message).to_string(),
        ),
        Err(_) => (
            Status::Internal,
            error_value("internal", "the call panicked").to_string(),
        ),
    };
    // SAFETY: `out` is not null and the caller guarantees it is writable.
    unsafe { write(out, text) };
    status
}

/// Write `count` to `out` when it is not null.
///
/// # Safety
///
/// `out` must be null or writable.
unsafe fn write_count(out: *mut usize, count: usize) {
    if !out.is_null() {
        // SAFETY: the caller guarantees `out` is writable.
        unsafe { out.write(count) };
    }
}

/// Comma-separated `key:value` tags, empty ones dropped.
fn constant_tags_of(tags: Option<&str>) -> Result<Vec<&str>, Failure> {
    let tags = tags.ok_or(Failure::Internal("constant_tags is not UTF-8"))?;
    Ok(tags
        .split(',')
        .map(str::trim)
        .filter(|tag| !tag.is_empty())
        .collect())
}

enum Failure {
    Rejected(MetricError),
    Internal(&'static str),
}

impl From<MetricError> for Failure {
    fn from(error: MetricError) -> Self {
        Failure::Rejected(error)
    }
}

fn invalid(message: impl Into<String>) -> Failure {
    Failure::Rejected(MetricError::new(ErrorCode::FieldTypeInvalid, message))
}

fn parse_document(input: Option<&[u8]>) -> Result<Json, Failure> {
    let input = input.ok_or(Failure::Internal("the input is null"))?;
    let text = std::str::from_utf8(input).map_err(|_| invalid("the input is not UTF-8"))?;
    Json::parse(text).map_err(|error| invalid(error.to_string()))
}

/// The projection a request document asks for: `profile`, `observation`,
/// optional `deployment_attributes`, and an optional `metrics` list that
/// keeps only those metrics.
fn projection_of(document: &Json) -> Result<(Profile, libdd_ai_usage::Projection), Failure> {
    projection_with(document, &BatchSettings::default())
}

/// The metric list a batch applies to every document that does not state
/// its own.
#[derive(Default)]
struct BatchSettings {
    metrics: Option<Vec<String>>,
}

/// [`projection_of`], with `defaults` for what the document leaves out.
fn projection_with(
    document: &Json,
    defaults: &BatchSettings,
) -> Result<(Profile, libdd_ai_usage::Projection), Failure> {
    let id = document
        .get("profile")
        .and_then(Json::as_str)
        .ok_or_else(|| MetricError::new(ErrorCode::RequiredFieldMissing, "profile is required"))?;
    let profile = Profile::from_id(id).ok_or_else(|| {
        MetricError::new(
            ErrorCode::ProfileInvalid,
            format!("unsupported profile: {id}"),
        )
    })?;
    let observation = document.get(profile.input_key()).unwrap_or(&Json::Null);
    let projection = project_result(profile, observation)?;
    let deployment = document.get("deployment_attributes").unwrap_or(&Json::Null);
    let mut projection = with_deployment_attributes_json(projection, deployment)?;
    match document.get("metrics") {
        None | Some(Json::Null) => {
            if let Some(names) = &defaults.metrics {
                retain_metrics(&mut projection, names);
            }
        }
        Some(Json::Array(names)) => {
            let names = names
                .iter()
                .map(|name| {
                    name.as_str()
                        .ok_or_else(|| invalid("metrics must be strings"))
                })
                .collect::<Result<Vec<&str>, Failure>>()?;
            retain_metrics(&mut projection, &names);
        }
        Some(_) => return Err(invalid("metrics must be an array of strings")),
    }
    Ok((profile, projection))
}

fn issues(projection: &libdd_ai_usage::Projection) -> Value {
    json!(
        projection
            .issues
            .iter()
            .map(|issue| issue.as_str())
            .collect::<Vec<_>>()
    )
}

/// Project the request document `input[..input_len]` into its Datadog
/// series and write `{"series": [{"name", "type", "value", "tags"}],
/// "issues": [...]}` to `out`.
///
/// The document is `{"profile": "{id}@{version}", "observation": {...},
/// "deployment_attributes": {...}, "metrics": [...]}`; the last two are
/// optional.
///
/// # Safety
///
/// `input` must point to `input_len` readable bytes (or `input_len` must be
/// 0), and `out` must be null or point to a writable [`Buffer`], released
/// with [`ddog_ai_usage_buffer_drop`].
#[unsafe(no_mangle)]
pub unsafe extern "C" fn ddog_ai_usage_project(
    input: *const u8,
    input_len: usize,
    out: *mut Buffer,
) -> Status {
    // SAFETY: forwarded from the caller.
    unsafe {
        json_call(out, || {
            catch_unwind(AssertUnwindSafe(|| {
                let document = parse_document(bytes(input, input_len))?;
                let (profile, projection) = projection_of(&document)?;
                let series =
                    datadog_series(profile, &projection.points, &projection.resource, false)?;
                Ok(json!({
                    "series": series
                        .iter()
                        .map(|s| json!({
                            "name": s.name,
                            "type": s.series_type.as_str(),
                            "value": s.value,
                            "tags": s.tags,
                        }))
                        .collect::<Vec<_>>(),
                    "issues": issues(&projection),
                }))
            }))
            .unwrap_or(Err(Failure::Internal("the projection panicked")))
        })
    }
}

/// Create an empty [`Batch`] and write it to `out`. Release it with
/// [`ddog_ai_usage_batch_drop`].
///
/// # Safety
///
/// `out` must be null or writable.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn ddog_ai_usage_batch_new(out: *mut *mut Batch) -> Status {
    if out.is_null() {
        return Status::Internal;
    }
    let batch = catch_unwind(|| {
        Box::into_raw(Box::new(Batch {
            inner: Mutex::new(MetricBatch::new()),
            settings: Mutex::new(BatchSettings::default()),
        }))
    });
    match batch {
        Ok(batch) => {
            // SAFETY: `out` is not null and the caller guarantees it is
            // writable.
            unsafe { out.write(batch) };
            Status::Ok
        }
        Err(_) => Status::Internal,
    }
}

/// Add every observation of one request to `batch` together: `input[..input_len]`
/// is a JSON array of request documents, each `{"profile", "observation",
/// "deployment_attributes", "metrics"}` as [`ddog_ai_usage_project`] reads
/// it (its provider attempts, token breakdowns and gateway request).
/// Either all are added or none: a bounded batch without room for all of
/// them drops them all, so it never keeps an attempt without its breakdown,
/// and counts each in [`ddog_ai_usage_batch_dropped`]. A rejected document
/// rejects the request, adds nothing, and writes `{"error": {"code",
/// "message"}}` whose message names the document's index. On success writes
/// `{"issues": [[...], ...], "dropped": false}` (one issue list per
/// document) to `out`, or nothing when `out` is null.
///
/// # Safety
///
/// `batch` must be a live batch from [`ddog_ai_usage_batch_new`], `input`
/// must point to `input_len` readable bytes (or `input_len` must be 0), and
/// `out` must be null or writable.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn ddog_ai_usage_batch_add_request(
    batch: *const Batch,
    input: *const u8,
    input_len: usize,
    out: *mut Buffer,
) -> Status {
    let result = catch_unwind(AssertUnwindSafe(|| {
        // SAFETY: the caller guarantees a live batch or null.
        let batch = unsafe { batch.as_ref() }.ok_or(Failure::Internal("the batch is null"))?;
        // SAFETY: forwarded from the caller.
        let request = parse_document(unsafe { bytes(input, input_len) })?;
        let documents = request
            .as_array()
            .ok_or_else(|| invalid("a request must be an array of documents"))?;
        let defaults = batch_metrics(batch)?;
        let defaults: Option<Vec<&str>> = defaults
            .as_ref()
            .map(|names| names.iter().map(String::as_str).collect());
        let mut decoded = Vec::with_capacity(documents.len());
        for (at, document) in documents.iter().enumerate() {
            match decode_document(document) {
                Ok(document) => decoded.push(document),
                Err(failure) => {
                    // An earlier document that is rejected is the one reported.
                    let earlier = request_documents(&decoded, defaults.as_deref());
                    if let Err(error) = MetricBatch::new().try_add_request(&earlier) {
                        return Err(document_failure(error));
                    }
                    return Err(match failure {
                        Failure::Rejected(error) => Failure::Rejected(MetricError::new(
                            error.code(),
                            format!("document {at}: {}", error.message()),
                        )),
                        internal => internal,
                    });
                }
            }
        }
        let documents = request_documents(&decoded, defaults.as_deref());
        add_documents(batch, &documents)
    }))
    .unwrap_or(Err(Failure::Internal("adding to the batch panicked")));
    // SAFETY: forwarded from the caller.
    unsafe { added_status(result, out) }
}

/// An observation decoded from a request document. A request holds a few,
/// so they are not boxed.
#[allow(clippy::large_enum_variant)]
enum OwnedObservation {
    Attempt(ProviderAttemptObservation),
    Streaming(ProviderStreamingObservation),
    Breakdown(TokenBreakdownObservation),
    Gateway(GatewayRequestObservation),
}

impl OwnedObservation {
    fn as_ref(&self) -> Observation<'_> {
        match self {
            OwnedObservation::Attempt(o) => Observation::ProviderAttempt(o),
            OwnedObservation::Streaming(o) => Observation::ProviderStreaming(o),
            OwnedObservation::Breakdown(o) => Observation::TokenBreakdown(o),
            OwnedObservation::Gateway(o) => Observation::GatewayRequest(o),
        }
    }
}

/// A request document decoded: its observation, its deployment attributes,
/// and the metrics it keeps (`None`: the batch's list).
struct DecodedDocument<'j> {
    observation: OwnedObservation,
    deployment: Vec<(&'j str, Option<&'j str>)>,
    metrics: Option<Vec<&'j str>>,
}

fn decode_document(document: &Json) -> Result<DecodedDocument<'_>, Failure> {
    let id = document
        .get("profile")
        .and_then(Json::as_str)
        .ok_or_else(|| MetricError::new(ErrorCode::RequiredFieldMissing, "profile is required"))?;
    let profile = Profile::from_id(id).ok_or_else(|| {
        MetricError::new(
            ErrorCode::ProfileInvalid,
            format!("unsupported profile: {id}"),
        )
    })?;
    let input = document.get(profile.input_key()).unwrap_or(&Json::Null);
    let observation = match profile {
        Profile::ProviderAttempt => {
            OwnedObservation::Attempt(ProviderAttemptObservation::from_json(input)?)
        }
        Profile::ProviderStreaming => {
            OwnedObservation::Streaming(ProviderStreamingObservation::from_json(input)?)
        }
        Profile::TokenBreakdown => {
            OwnedObservation::Breakdown(TokenBreakdownObservation::from_json(input)?)
        }
        Profile::GatewayRequest => {
            OwnedObservation::Gateway(GatewayRequestObservation::from_json(input)?)
        }
    };
    let deployment = match document.get("deployment_attributes") {
        None | Some(Json::Null) => Vec::new(),
        Some(Json::Object(members)) => members
            .iter()
            .filter(|(_, value)| !value.is_null())
            .map(|(name, value)| (name.as_str(), value.as_str()))
            .collect(),
        Some(_) => {
            return Err(Failure::Rejected(MetricError::new(
                ErrorCode::FieldTypeInvalid,
                "deployment attributes must be an object",
            )));
        }
    };
    let metrics = match document.get("metrics") {
        None | Some(Json::Null) => None,
        Some(Json::Array(names)) => Some(
            names
                .iter()
                .map(|name| {
                    name.as_str()
                        .ok_or_else(|| invalid("metrics must be strings"))
                })
                .collect::<Result<Vec<&str>, Failure>>()?,
        ),
        Some(_) => return Err(invalid("metrics must be an array of strings")),
    };
    Ok(DecodedDocument {
        observation,
        deployment,
        metrics,
    })
}

fn request_documents<'d>(
    decoded: &'d [DecodedDocument<'_>],
    defaults: Option<&'d [&'d str]>,
) -> Vec<Document<'d>> {
    decoded
        .iter()
        .map(|document| Document {
            observation: document.observation.as_ref(),
            deployment_attributes: &document.deployment,
            metrics: document.metrics.as_deref().or(defaults),
        })
        .collect()
}

/// The metric list a batch applies to documents that state none.
fn batch_metrics(batch: &Batch) -> Result<Option<Vec<String>>, Failure> {
    Ok(batch
        .settings
        .lock()
        .map_err(|_| Failure::Internal("the batch is poisoned"))?
        .metrics
        .clone())
}

fn document_failure(error: DocumentError) -> Failure {
    Failure::Rejected(MetricError::new(
        error.error.code(),
        format!("document {}: {}", error.document, error.error.message()),
    ))
}

/// Add a request's documents to `batch`: their issues and whether they were
/// added.
fn add_documents(
    batch: &Batch,
    documents: &[Document<'_>],
) -> Result<(Vec<Issues>, bool), Failure> {
    let mut inner = batch
        .inner
        .lock()
        .map_err(|_| Failure::Internal("the batch is poisoned"))?;
    let (added, issues) = inner.try_add_request(documents).map_err(document_failure)?;
    Ok((issues, added))
}

/// The status of an add, with its issues or rejection written to `out`
/// when it is not null.
///
/// # Safety
///
/// `out` must be null or writable.
unsafe fn added_status(result: Result<(Vec<Issues>, bool), Failure>, out: *mut Buffer) -> Status {
    let (status, value) = match result {
        Ok(_) if out.is_null() => return Status::Ok,
        Ok((issues, added)) => (
            Status::Ok,
            json!({
                "issues": issues
                    .iter()
                    .map(|issues| issues.iter().map(|issue| issue.as_str()).collect::<Vec<_>>())
                    .collect::<Vec<_>>(),
                "dropped": !added,
            }),
        ),
        Err(Failure::Rejected(error)) => (Status::Rejected, rejection(&error)),
        Err(Failure::Internal(message)) => (Status::Internal, error_value("internal", message)),
    };
    if !out.is_null() {
        let text = catch_unwind(|| value.to_string()).unwrap_or_default();
        // SAFETY: `out` is not null and the caller guarantees it is writable.
        unsafe { write(out, text) };
    }
    status
}

/// Set the metric list `input[..input_len]` (a JSON array of names, as a
/// request document's `metrics` states it) that `batch` keeps of every
/// document stating none. Parsed once here rather than in every document.
///
/// **An empty list `[]` keeps no metric**, as `"metrics": []` in a document
/// does: every observation added then projects to nothing. `null` or
/// zero-length input keeps every metric again.
///
/// # Safety
///
/// `batch` must be a live batch from [`ddog_ai_usage_batch_new`], `input`
/// must point to `input_len` readable bytes (or `input_len` must be 0), and
/// `out` must be null or writable.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn ddog_ai_usage_batch_set_metrics(
    batch: *const Batch,
    input: *const u8,
    input_len: usize,
    out: *mut Buffer,
) -> Status {
    // SAFETY: forwarded from the caller.
    unsafe {
        json_call(out, || {
            catch_unwind(AssertUnwindSafe(|| {
                // SAFETY: the caller guarantees a live batch or null.
                let batch = batch
                    .as_ref()
                    .ok_or(Failure::Internal("the batch is null"))?;
                let metrics = if input_len == 0 {
                    None
                } else {
                    match parse_document(bytes(input, input_len))? {
                        Json::Null => None,
                        Json::Array(names) => Some(
                            names
                                .iter()
                                .map(|name| {
                                    name.as_str()
                                        .map(str::to_string)
                                        .ok_or_else(|| invalid("metrics must be strings"))
                                })
                                .collect::<Result<Vec<String>, Failure>>()?,
                        ),
                        _ => return Err(invalid("metrics must be an array of strings")),
                    }
                };
                batch
                    .settings
                    .lock()
                    .map_err(|_| Failure::Internal("the batch is poisoned"))?
                    .metrics = metrics;
                Ok(json!({}))
            }))
            .unwrap_or(Err(Failure::Internal("setting the metrics panicked")))
        })
    }
}

/// Whether `batch` holds no points. A null batch is empty.
///
/// # Safety
///
/// `batch` must be null or a live batch from [`ddog_ai_usage_batch_new`].
#[unsafe(no_mangle)]
pub unsafe extern "C" fn ddog_ai_usage_batch_is_empty(batch: *const Batch) -> bool {
    catch_unwind(AssertUnwindSafe(|| {
        // SAFETY: the caller guarantees a live batch or null.
        unsafe { batch.as_ref() }.is_none_or(|batch| {
            batch
                .inner
                .lock()
                .map(|inner| inner.is_empty())
                .unwrap_or(true)
        })
    }))
    .unwrap_or(true)
}

/// The number of points `batch` holds: one per Counter series and one per
/// Histogram sample. For a flush threshold, not a line count: the
/// DogStatsD lines taken can be more (each Histogram series also writes a
/// `.count` and a `.sum` line) or fewer (series whose tags normalize alike
/// share their lines). A null batch holds none.
///
/// # Safety
///
/// `batch` must be null or a live batch from [`ddog_ai_usage_batch_new`].
#[unsafe(no_mangle)]
pub unsafe extern "C" fn ddog_ai_usage_batch_len(batch: *const Batch) -> usize {
    catch_unwind(AssertUnwindSafe(|| {
        // SAFETY: the caller guarantees a live batch or null.
        unsafe { batch.as_ref() }.map_or(0, |batch| {
            batch.inner.lock().map(|inner| inner.len()).unwrap_or(0)
        })
    }))
    .unwrap_or(0)
}

/// The points of `batch`, leaving it empty with its bound and dropped count.
fn take_batch(batch: &Batch) -> Result<MetricBatch, Failure> {
    Ok(batch
        .inner
        .lock()
        .map_err(|_| Failure::Internal("the batch is poisoned"))?
        .take())
}

/// Take every point of `batch`, leaving it empty, and write it as DogStatsD
/// datagrams of at most `max_payload` bytes ([`UDP_MAX_PAYLOAD`] or
/// [`UDS_MAX_PAYLOAD`]), as text: each datagram's lines joined by `\n`,
/// datagrams separated by a NUL byte, no trailing NUL. `constant_tags` is a
/// comma-separated list of `key:value` tags added to every line, such as the
/// client's `env`; it may be empty. A line longer than `max_payload` with
/// its tags goes alone in a datagram of its own; only one longer than
/// [`MAX_LINE_BYTES`] (or `max_payload`, if larger) is dropped, and the
/// number dropped is written to `dropped_lines` when it is not null. An empty
/// batch writes an empty buffer.
///
/// # Safety
///
/// `batch` must be a live batch from [`ddog_ai_usage_batch_new`],
/// `constant_tags` must point to `constant_tags_len` readable bytes (or
/// `constant_tags_len` must be 0), `dropped_lines` must be null or writable,
/// and `out` must be null or writable.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn ddog_ai_usage_batch_take_dogstatsd_text(
    batch: *const Batch,
    constant_tags: *const u8,
    constant_tags_len: usize,
    max_payload: usize,
    dropped_lines: *mut usize,
    out: *mut Buffer,
) -> Status {
    // SAFETY: forwarded from the caller.
    unsafe {
        text_or_error_call(out, || {
            catch_unwind(AssertUnwindSafe(|| {
                // SAFETY: the caller guarantees a live batch or null.
                let batch = batch
                    .as_ref()
                    .ok_or(Failure::Internal("the batch is null"))?;
                let tags = constant_tags_of(text(constant_tags, constant_tags_len))?;
                let lines = take_batch(batch)?.dogstatsd_lines()?;
                let (text, dropped) = pack_dogstatsd_joined(
                    lines.iter().map(String::as_str),
                    &tags,
                    max_payload,
                    '\0',
                );
                write_count(dropped_lines, dropped);
                Ok(text)
            }))
            .unwrap_or(Err(Failure::Internal("encoding the batch panicked")))
        })
    }
}

/// Bound `batch` to at most `max_len` points (as
/// [`ddog_ai_usage_batch_len`] counts them), or lift the bound with 0. An
/// observation that would take the batch past its bound is dropped whole
/// and counted by [`ddog_ai_usage_batch_dropped`]. Points already held are
/// kept; taking the batch keeps the bound. A null batch is a no-op.
///
/// # Safety
///
/// `batch` must be null or a live batch from [`ddog_ai_usage_batch_new`].
#[unsafe(no_mangle)]
pub unsafe extern "C" fn ddog_ai_usage_batch_set_max_len(batch: *const Batch, max_len: usize) {
    let _ = catch_unwind(AssertUnwindSafe(|| {
        // SAFETY: the caller guarantees a live batch or null.
        if let Some(batch) = unsafe { batch.as_ref() }
            && let Ok(mut inner) = batch.inner.lock()
        {
            inner.set_max_len((max_len != 0).then_some(max_len));
        }
    }));
}

/// The observations `batch` dropped because it was full, since it was
/// created. Taking the batch does not reset it, so a caller reports the
/// difference since its last flush. A null batch dropped none.
///
/// # Safety
///
/// `batch` must be null or a live batch from [`ddog_ai_usage_batch_new`].
#[unsafe(no_mangle)]
pub unsafe extern "C" fn ddog_ai_usage_batch_dropped(batch: *const Batch) -> u64 {
    catch_unwind(AssertUnwindSafe(|| {
        // SAFETY: the caller guarantees a live batch or null.
        unsafe { batch.as_ref() }.map_or(0, |batch| {
            batch.inner.lock().map(|inner| inner.dropped()).unwrap_or(0)
        })
    }))
    .unwrap_or(0)
}

/// Standard base64 with padding, for binary values inside JSON output.
fn base64(bytes: &[u8]) -> String {
    const ALPHABET: &[u8; 64] = b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
    let mut out = String::with_capacity(bytes.len().div_ceil(3) * 4);
    for chunk in bytes.chunks(3) {
        let b = [
            chunk[0],
            chunk.get(1).copied().unwrap_or(0),
            chunk.get(2).copied().unwrap_or(0),
        ];
        let n = (u32::from(b[0]) << 16) | (u32::from(b[1]) << 8) | u32::from(b[2]);
        for (i, shift) in [18, 12, 6, 0].into_iter().enumerate() {
            if i <= chunk.len() {
                out.push(char::from(ALPHABET[((n >> shift) & 63) as usize]));
            } else {
                out.push('=');
            }
        }
    }
    out
}

/// Tag every series [`ddog_ai_usage_batch_take_series`] takes from `batch`
/// with this writer's `host.name` (`host[..host_len]`, normalized as Datadog
/// stores a tag value; empty leaves it out) and `process.pid` (`pid`), so
/// replicas and processes never share a series. A null batch is a no-op.
///
/// # Safety
///
/// `batch` must be null or a live batch from [`ddog_ai_usage_batch_new`],
/// and `host` must point to `host_len` readable bytes (or `host_len` must be
/// 0).
#[unsafe(no_mangle)]
pub unsafe extern "C" fn ddog_ai_usage_batch_set_writer(
    batch: *const Batch,
    host: *const u8,
    host_len: usize,
    pid: u32,
) {
    let _ = catch_unwind(AssertUnwindSafe(|| {
        // SAFETY: the caller guarantees a live batch or null, and readable
        // bytes.
        if let (Some(batch), Some(host)) = unsafe { (batch.as_ref(), text(host, host_len)) }
            && let Ok(mut inner) = batch.inner.lock()
        {
            inner.set_writer(host, pid);
        }
    }));
}

/// Take every point of `batch`, leaving it empty, as Datadog metrics intake
/// takes it from a writer that submits to the API, and write
/// `{"timestamp", "interval", "dropped", "series": [{"metric", "tags",
/// "value"}], "distributions": [{"metric", "tags", "sketch"}]}` to `out`:
///
/// - `series` are RATE points over `interval_secs` (0 is read as 1): the sum since the last take
///   divided by the interval, to submit with type RATE, that interval and aggregation SUM. The
///   `.count` and `.sum` companions of distributions are among them.
/// - `distributions` hold one sketch per series, `sketch` being the base64 of intake's
///   `sketchpb.Sparse` protobuf (keys and counts with min, max, count and sum), as metrics intake
///   computes a DDSketch (relative accuracy 1/128, 4096 bins).
/// - Every point is stamped at `timestamp`: `now_unix_seconds` (0 for the system clock), or the
///   second after this batch's previous take when that is later, so one writer never writes a
///   series twice at the same second.
/// - `tags` are sorted and carry the writer's tags (see [`ddog_ai_usage_batch_set_writer`]).
/// - `dropped` is the observations the batch dropped since the last take.
///
/// # Safety
///
/// `batch` must be a live batch from [`ddog_ai_usage_batch_new`], and `out`
/// must be null or writable.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn ddog_ai_usage_batch_take_series(
    batch: *const Batch,
    interval_secs: u32,
    now_unix_seconds: i64,
    out: *mut Buffer,
) -> Status {
    // SAFETY: forwarded from the caller.
    unsafe {
        json_call(out, || {
            catch_unwind(AssertUnwindSafe(|| {
                // SAFETY: the caller guarantees a live batch or null.
                let batch = batch
                    .as_ref()
                    .ok_or(Failure::Internal("the batch is null"))?;
                let now = if now_unix_seconds == 0 {
                    std::time::SystemTime::now()
                        .duration_since(std::time::UNIX_EPOCH)
                        .map_or(0, |elapsed| {
                            i64::try_from(elapsed.as_secs()).unwrap_or(i64::MAX)
                        })
                } else {
                    now_unix_seconds
                };
                let taken = batch
                    .inner
                    .lock()
                    .map_err(|_| Failure::Internal("the batch is poisoned"))?
                    .take_intake(interval_secs, now)?;
                Ok(json!({
                    "timestamp": taken.timestamp,
                    "interval": taken.interval,
                    "dropped": taken.dropped,
                    "series": taken.rates.iter().map(|s| json!({
                        "metric": s.metric,
                        "tags": s.tags,
                        "value": s.value,
                    })).collect::<Vec<_>>(),
                    "distributions": taken.sketches.iter().map(|s| json!({
                        "metric": s.metric,
                        "tags": s.tags,
                        "sketch": base64(&s.sketch.encode_sparse()),
                    })).collect::<Vec<_>>(),
                }))
            }))
            .unwrap_or(Err(Failure::Internal("taking the batch panicked")))
        })
    }
}

/// Release a batch. A null batch is a no-op.
///
/// # Safety
///
/// `batch` must be null or a live batch from [`ddog_ai_usage_batch_new`],
/// released only once.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn ddog_ai_usage_batch_drop(batch: *mut Batch) {
    if batch.is_null() {
        return;
    }
    // SAFETY: `batch` came from `Box::into_raw` in `ddog_ai_usage_batch_new`.
    let batch = unsafe { Box::from_raw(batch) };
    // Dropping a batch only frees memory; a panic there is contained.
    let _ = catch_unwind(AssertUnwindSafe(|| drop(batch)));
}

fn format_of(name: Option<&str>) -> Result<UsageFormat, Failure> {
    let name = name.ok_or(Failure::Internal("format is not UTF-8"))?;
    let name = if name.is_empty() { "auto" } else { name };
    UsageFormat::from_name(name).ok_or_else(|| {
        Failure::Rejected(MetricError::new(
            ErrorCode::ValueNotAllowed,
            format!("unknown usage format: {name}"),
        ))
    })
}

/// A provider response as JSON: the observation's usage members, the model
/// and tier named, how the stream ended, and its `error.type`.
fn response_value(
    response: &ProviderResponse,
    outcome: StreamOutcome,
    error_name: Option<&str>,
    inclusive: bool,
) -> Value {
    // A failure that names no cause is `api_error`.
    let error_type = (outcome == StreamOutcome::Failed)
        .then(|| classify_error(error_name, None).unwrap_or(ERROR_TYPE_API));
    json!({
        "usage": if inclusive {
            response.usage.as_ref().map(|usage| usage.inclusive())
        } else {
            response.usage.clone()
        },
        "response_model": response.response_model,
        "service_tier": response.service_tier,
        "outcome": outcome.as_str(),
        "error_name": error_name,
        "error_type": error_type,
        "error_code": response.error.as_ref().and_then(|e| e.code.as_deref()),
        "error_message": response.error.as_ref().and_then(|e| e.message.as_deref()),
        "issues": response.issues,
    })
}

/// Read a whole provider response body (`body[..body_len]`: a JSON
/// document, or a buffered stream of server-sent events) in the usage
/// `format` (`auto`, `openai_chat`, `openai_responses`, `anthropic`,
/// `gemini` or `gemini_openai_compat`; empty is `auto`), and write
/// `{"usage": {...} | null, "response_model", "service_tier", "outcome",
/// "error_name", "error_type", "error_code", "error_message", "issues"}` to
/// `out`. `issues` says why something reported was not kept:
/// `service_tier_dropped` for a tier outside `^[A-Za-z0-9._-]{1,32}$`, and
/// `response_model_dropped` for a served model outside the deployment value
/// grammar (so a provider cannot mint tag values from free text).
/// `usage` holds the members to merge into an observation. Its
/// `input_tokens_by_modality` and `output_tokens_by_modality` hold the
/// provider's own `image` and `audio` parts, counted within the totals:
/// OpenAI-shaped usage reports image output tokens (image generation) as
/// `output_tokens_by_modality.image`, which a caller prices at the model's
/// image rate. `error_code` and
/// `error_message` are the provider's own, from the body or an in-band
/// stream error: control characters removed, the message cut to 256 bytes,
/// so a gateway can log them without parsing the error itself. `embeddings`
/// is true for an embeddings operation.
///
/// # Safety
///
/// `format` and `body` must point to their lengths of readable bytes (or the
/// length must be 0), and `out` must be null or writable.
// allow(ffi-panic-boundary): delegates to `_with`, which catches panics.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn ddog_ai_usage_parse_provider_response(
    format: *const u8,
    format_len: usize,
    embeddings: bool,
    body: *const u8,
    body_len: usize,
    out: *mut Buffer,
) -> Status {
    // SAFETY: forwarded from the caller.
    unsafe {
        ddog_ai_usage_parse_provider_response_with(
            format, format_len, embeddings, 0, body, body_len, out,
        )
    }
}

/// [`ddog_ai_usage_parse_provider_response`] with `options`, a bit set:
/// [`INCLUSIVE_TOTALS`] reports usage with inclusive totals. Unknown bits
/// are [`Status::Rejected`].
///
/// # Safety
///
/// As [`ddog_ai_usage_parse_provider_response`].
#[unsafe(no_mangle)]
pub unsafe extern "C" fn ddog_ai_usage_parse_provider_response_with(
    format: *const u8,
    format_len: usize,
    embeddings: bool,
    options: u32,
    body: *const u8,
    body_len: usize,
    out: *mut Buffer,
) -> Status {
    // SAFETY: forwarded from the caller.
    unsafe {
        json_call(out, || {
            catch_unwind(AssertUnwindSafe(|| {
                let inclusive = options_of(options)?;
                let format = format_of(text(format, format_len))?;
                let body = bytes(body, body_len).ok_or(Failure::Internal("the body is null"))?;
                let (response, outcome, error) = parse_provider_body(format, body, embeddings);
                Ok(response_value(
                    &response,
                    outcome,
                    error.as_deref(),
                    inclusive,
                ))
            }))
            .unwrap_or(Err(Failure::Internal("reading the response panicked")))
        })
    }
}

/// Whether `options` asks for inclusive totals; unknown bits are refused.
fn options_of(options: u32) -> Result<bool, Failure> {
    if options & !INCLUSIVE_TOTALS != 0 {
        return Err(invalid(format!("unknown options: {options:#x}")));
    }
    Ok(options & INCLUSIVE_TOTALS != 0)
}

/// Start reading a provider stream in the usage `format`, as
/// [`ddog_ai_usage_parse_provider_response`] names them, and write the
/// stream to `out`. Release it with [`ddog_ai_usage_stream_drop`].
///
/// # Safety
///
/// `format` must point to `format_len` readable bytes (or `format_len` must
/// be 0), and `out` must be null or writable.
// allow(ffi-panic-boundary): delegates to `_with`, which catches panics.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn ddog_ai_usage_stream_new(
    format: *const u8,
    format_len: usize,
    embeddings: bool,
    out: *mut *mut Stream,
) -> Status {
    // SAFETY: forwarded from the caller.
    unsafe { ddog_ai_usage_stream_new_with(format, format_len, embeddings, 0, out) }
}

/// [`ddog_ai_usage_stream_new`] with `options`, as
/// [`ddog_ai_usage_parse_provider_response_with`] reads them: with
/// [`INCLUSIVE_TOTALS`], `_take` reports inclusive totals.
///
/// # Safety
///
/// As [`ddog_ai_usage_stream_new`].
#[unsafe(no_mangle)]
pub unsafe extern "C" fn ddog_ai_usage_stream_new_with(
    format: *const u8,
    format_len: usize,
    embeddings: bool,
    options: u32,
    out: *mut *mut Stream,
) -> Status {
    if out.is_null() {
        return Status::Internal;
    }
    let created = catch_unwind(AssertUnwindSafe(|| {
        let inclusive = options_of(options)?;
        // SAFETY: forwarded from the caller.
        let format = format_of(unsafe { text(format, format_len) })?;
        Ok::<_, Failure>(Box::into_raw(Box::new(Stream {
            inner: UsageStream::new(format, embeddings),
            inclusive,
        })))
    }));
    match created {
        Ok(Ok(stream)) => {
            // SAFETY: `out` is not null and the caller guarantees it is
            // writable.
            unsafe { out.write(stream) };
            Status::Ok
        }
        Ok(Err(Failure::Rejected(_))) => Status::Rejected,
        Ok(Err(Failure::Internal(_))) | Err(_) => Status::Internal,
    }
}

/// Read the next `chunk[..chunk_len]` of the stream, which may end anywhere.
///
/// # Safety
///
/// `stream` must be a live stream from [`ddog_ai_usage_stream_new`], not used
/// by another thread during the call, and `chunk` must point to `chunk_len`
/// readable bytes (or `chunk_len` must be 0).
#[unsafe(no_mangle)]
pub unsafe extern "C" fn ddog_ai_usage_stream_feed(
    stream: *mut Stream,
    chunk: *const u8,
    chunk_len: usize,
) -> Status {
    catch_unwind(AssertUnwindSafe(|| {
        // SAFETY: the caller guarantees a live stream or null, and readable
        // bytes.
        match (unsafe { stream.as_mut() }, unsafe {
            bytes(chunk, chunk_len)
        }) {
            (Some(stream), Some(chunk)) => {
                stream.inner.feed(chunk);
                Status::Ok
            }
            _ => Status::Internal,
        }
    }))
    .unwrap_or(Status::Internal)
}

/// Read one server-sent event the caller already split from the stream: its
/// `event` field `event_name[..event_name_len]` (empty when it had none) and
/// its `data` `data[..data_len]` (the JSON payload or `[DONE]`; may be
/// empty). The event is read as [`ddog_ai_usage_stream_feed`] reads it from
/// the stream, and can be mixed with it on one stream.
///
/// # Safety
///
/// `stream` must be a live stream from [`ddog_ai_usage_stream_new`], not used
/// by another thread during the call, and `event_name` and `data` must point
/// to their lengths of readable bytes (or the length must be 0).
#[unsafe(no_mangle)]
pub unsafe extern "C" fn ddog_ai_usage_stream_feed_event(
    stream: *mut Stream,
    event_name: *const u8,
    event_name_len: usize,
    data: *const u8,
    data_len: usize,
) -> Status {
    catch_unwind(AssertUnwindSafe(|| {
        // SAFETY: the caller guarantees a live stream or null, and readable
        // bytes.
        let (stream, name, data) = unsafe {
            (
                stream.as_mut(),
                text(event_name, event_name_len),
                text(data, data_len),
            )
        };
        match (stream, name, data) {
            (Some(stream), Some(name), Some(data)) => {
                stream.inner.feed_event(name, data);
                Status::Ok
            }
            _ => Status::Internal,
        }
    }))
    .unwrap_or(Status::Internal)
}

/// Write what the stream reported, as
/// [`ddog_ai_usage_parse_provider_response`] does, reading a last line that
/// had no line ending, and release the stream, taking its state rather than
/// copying it. The stream must not be used afterwards, and
/// is released even when the call fails. A null stream is
/// [`Status::Internal`].
///
/// # Safety
///
/// `stream` must be null or a live stream from [`ddog_ai_usage_stream_new`],
/// released only once, and `out` must be null or writable.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn ddog_ai_usage_stream_take(
    stream: *mut Stream,
    out: *mut Buffer,
) -> Status {
    if stream.is_null() {
        // SAFETY: forwarded from the caller.
        return unsafe { json_call(out, || Err(Failure::Internal("the stream is null"))) };
    }
    // SAFETY: `stream` came from `Box::into_raw` in `ddog_ai_usage_stream_new`.
    let stream = unsafe { Box::from_raw(stream) };
    // SAFETY: forwarded from the caller.
    unsafe {
        json_call(out, move || {
            catch_unwind(AssertUnwindSafe(move || {
                let inclusive = stream.inclusive;
                let (response, outcome, error) = stream.inner.finish();
                Ok(response_value(
                    &response,
                    outcome,
                    error.as_deref(),
                    inclusive,
                ))
            }))
            .unwrap_or(Err(Failure::Internal("reading the stream panicked")))
        })
    }
}

/// Release a stream. A null stream is a no-op.

//! A C interface to [`libdd_ai_usage`], so that a gateway or integration in
//! any language (Go through dlopen, Lua through LuaJIT's FFI, Python through
//! ctypes or a native module) emits the same LLM usage and cost metrics from
//! the same provider responses.
//!
//! Structured values cross the boundary as UTF-8 JSON, so the only types in
//! the interface are bytes, two opaque handles and a status. Every function
//! takes its input as a pointer and a length and writes any output to a
//! [`Buffer`] the caller releases with [`ddog_ai_usage_buffer_drop`]; no
//! structure is passed by value, which keeps the interface usable from
//! loaders that cannot pass one. A panic never crosses the boundary: it is
//! reported as [`Status::Internal`].
//!
//! - Projection: [`ddog_ai_usage_project`] for one observation's Datadog series, and a [`Batch`]
//!   that collects projections over an export window and hands them out as packed DogStatsD
//!   datagrams.
//! - Provider responses: [`ddog_ai_usage_parse_provider_response`] for a whole body, and a
//!   [`Stream`] that reads server-sent events as they pass through.
//! - The shared vocabularies: provider names, `error.type`, provider account and project ids, and
//!   the grammars of service tiers, deployment values and person ids.
//!
//! The C header is `include/ai_usage.h`, generated by cbindgen.


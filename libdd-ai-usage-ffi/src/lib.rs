/// Run a call whose output is text: [`Status::Ok`] with the text in `out`,
/// [`Status::Rejected`] with an empty `out` when there is none.
///
/// # Safety
///
/// `out` must be null or writable.
unsafe fn text_call(out: *mut Buffer, call: impl FnOnce() -> Option<Option<String>>) -> Status {
    if out.is_null() {
        return Status::Internal;
    }
    let (status, text) = match catch_unwind(AssertUnwindSafe(call)) {
        Ok(Some(Some(text))) => (Status::Ok, text),
        Ok(Some(None)) => (Status::Rejected, String::new()),
        Ok(None) | Err(_) => (Status::Internal, String::new()),
    };
    // SAFETY: `out` is not null and the caller guarantees it is writable.
    unsafe { write(out, text) };
    status
}


//! A C interface to [`libdd_ai_usage`], so that a gateway or integration in
//! any language (Go through dlopen, Lua through LuaJIT's FFI, Python through
//! ctypes or a native module) emits the same LLM usage and cost metrics from
//! the same provider responses.
//!
//! The interface is a thin layer over the core crate, in libdatadog's common
//! FFI types: inputs are `ddog_CharSlice` (text and JSON) and `ddog_ByteSlice`
//! (provider bodies and stream chunks) passed by value; text and JSON outputs
//! are written to a `ddog_StringWrapper` the caller passes by pointer and
//! releases with `ddog_StringWrapper_drop`; the batch and the stream are
//! `Handle`s. A call that can fail returns a [`AiUsageError`] pointer, null on
//! success, released with [`ddog_ai_usage_error_free`]; no structure is
//! returned by value, which keeps the interface usable from loaders that
//! cannot receive one. With the `catch_panic` feature a panic never crosses
//! the boundary: it is reported as [`AiUsageErrorCode::Internal`].
//!
//! - Projection: [`ddog_ai_usage_project`] for one observation's Datadog series, and a [`Batch`]
//!   that collects projections over an export window and hands them out as intake series or packed
//!   DogStatsD datagrams.
//! - Provider responses: [`ddog_ai_usage_parse_provider_response`] for a whole body, and a
//!   [`Stream`] that reads server-sent events as they pass through.
//! - The shared vocabularies: provider names, `error.type`, provider account and project ids, and
//!   the grammars of service tiers, deployment values and person ids.
//!
//! The C header is `ai-usage.h`, generated by cbindgen at build time next to
//! libdatadog's `common.h`.


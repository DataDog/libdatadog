/// Release the bytes of a buffer this library wrote, and leave it empty. A
/// null or empty buffer is a no-op.
///
/// # Safety
///
/// `buffer` must be null or point to a [`Buffer`] this library wrote, whose
/// bytes were not released yet.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn ddog_ai_usage_buffer_drop(buffer: *mut Buffer) {
    let _ = catch_unwind(|| {
        // SAFETY: the caller guarantees a buffer this library wrote, or null.
        let Some(buffer) = (unsafe { buffer.as_mut() }) else {
            return;
        };
        let Buffer { ptr, len } = std::mem::replace(buffer, Buffer::EMPTY);
        if !ptr.is_null() {
            // SAFETY: `ptr` and `len` came from `Box::into_raw` of a boxed
            // slice in `Buffer::from_string`.
            drop(unsafe { Box::from_raw(ptr::slice_from_raw_parts_mut(ptr, len)) });
        }
    });
}

#[cfg(test)]
mod tests {
    use super::*;

    fn read(out: &mut Buffer) -> String {
        let text = if out.ptr.is_null() {
            String::new()
        } else {
            // SAFETY: the buffer was written by this library.
            let bytes = unsafe { slice::from_raw_parts(out.ptr, out.len) };
            String::from_utf8(bytes.to_vec()).unwrap()
        };
        // SAFETY: released once.
        unsafe { ddog_ai_usage_buffer_drop(out) };
        text
    }

    #[test]
    fn a_panic_is_an_internal_status() {
        let mut out = Buffer::EMPTY;
        // SAFETY: `out` is writable.
        let status = unsafe { json_call(&mut out, || panic!("boom")) };
        assert_eq!(status, Status::Internal);
        let value: Value = serde_json::from_str(&read(&mut out)).unwrap();
        assert_eq!(value["error"]["code"], "internal");

        let mut out = Buffer::EMPTY;
        // SAFETY: `out` is writable.
        let status = unsafe { text_call(&mut out, || panic!("boom")) };
        assert_eq!(status, Status::Internal);
        assert_eq!(read(&mut out), "");
    }

    #[test]
    fn an_empty_string_is_an_empty_buffer() {
        let buffer = Buffer::from_string(String::new());
        assert!(buffer.ptr.is_null());
        assert_eq!(buffer.len, 0);
    }
}
